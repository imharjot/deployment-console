const FALLBACK = (prefix: string): ServiceInfo => ({ label: prefix, category: "other", icon: "Puzzle" });

// "cloudfront:origin-request-policy" → "CloudFront origin request policy"; "ec2:ipam-pool" → "EC2 ipam pool".
function humanize(type: string, service: ServiceInfo): string {
  const rest = type.slice(type.indexOf(":") + 1);
  const words = rest.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[-_/:.]+/g, " ").trim().toLowerCase();
  return words ? `${service.label} ${words}` : service.label;
}

export function infoOf(type: string): { service: ServiceInfo; label: string; category: Category; visibility: Visibility } {
  const prefix = type.includes(":") ? type.slice(0, type.indexOf(":")) : type;
  const service = Object.hasOwn(SERVICES, prefix) ? SERVICES[prefix] : FALLBACK(prefix);
  const exact = Object.hasOwn(TYPES, type) ? TYPES[type] : undefined;
  const slash = type.indexOf("/");
  const baseType = slash > 0 ? type.slice(0, slash) : undefined;
  const base = baseType && Object.hasOwn(TYPES, baseType) ? TYPES[baseType] : undefined;
  const visibility: Visibility = exact?.visibility ?? (base?.visibility === "drop" ? "drop" : "table");
  return { service, label: exact?.label ?? humanize(type, service), category: exact?.category ?? base?.category ?? service.category, visibility };
}
