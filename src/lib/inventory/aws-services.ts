// The AWS service catalogue behind generic resources (kind "aws-resource", listed by the catch-all): what each ARN
// service prefix is called, which map column it belongs to, which icon it gets, and how each Resource Explorer type is
// shown. Pure (types only from ./types.ts), shared by the server and the UI.
//
// Types are spelled exactly as Resource Explorer spells them, sub-types included ("elasticloadbalancing:loadbalancer/app");
// ./aws-resource-types.json is the snapshot every key here is checked against (aws-services.test.ts).
//
// Visibility (CC-8):
// - "map": a node on the map. An allow-list of primary types: the long tail no first-class provider reads yet, plus the
//   types first-class providers cover (when that provider is denied, the generic row still shows where it belongs).
// - "table": a row in the All-resources table only — the default, so a noisy type nobody listed never clutters the map.
// - "drop": a sub-object (rules, versions, snapshots, sessions…), only counted in InventoryView.hiddenTypes.
// infoOf() looks the exact type up, then its base type (before the first "/"); a base type's "drop" is inherited, a
// base type's "map" is not (a sub-type of a primary type — "kendra:index/data-source" — is a table row).
